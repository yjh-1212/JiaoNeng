def base_control(f):
    code=f['code']; typ=f['type']
    if code=='credential_input': return '瞬时凭证输入（密码型遮罩）；不缓存/不输出'
    if code in ['state','resource_status','device_status','sync_status','notification_status']: return '状态标签＋发生时间/依据；通过动作生成'
    if code in ['reason','change_reason','rejection_reason','correction_reason','recommendation_note','message_text','answer_text','handling_action']: return '多行文本；可见标签与错误提示'
    if code in ['severity','verification_result','intent','report_mode','strategy_type']: return '受控单选/分段选择；只读时显示标签'
    if code in ['point','position','candidate_point','origin_point','destination_point']: return '位置选择＋地址/坐标系/精度说明；只读时对象摘要'
    if code in ['trajectory_points','load_series','green_output_series','predicted_load_series','arrival_series','queue_series']: return '时间曲线/序列图＋同口径可访问数据表'
    if code in ['dispatch_items','device_configuration','charge_discharge_bounds','investment_assumptions']: return '可增减复合行编辑器；每项按D3复合契约核验'
    if code in ['evidence_ids','proof_ids','closure_evidence']: return '获授权凭证关联/说明；不承诺未确认的上传类型和容量'
    if code=='operation_codes': return '按模块分组的操作复选清单＋组内搜索'
    if code in ['subject_scope','owner_subject_id']: return '授权主体树选择；上限外节点不可取得'
    if code in ['input_snapshot','business_context','result_refs','quality_flags','cost_coverage','evaluation_basis','metric_values','operation_result']: return '结构化摘要＋依据展开；不展示原始JSON'
    if '时间区间' in typ or 'time' in code and 'window' in code or 'windows' in code or 'window' in code: return '起止日期时间；可增减窗口行；显示时区'
    if typ=='时间' or code.endswith('_at'): return '日期时间控件；保留日期/时区与源粒度'
    if '十进制' in typ or '整数' in typ: return '数字输入/数值展示＋单位后缀；源精度保留'
    if '枚举数组' in typ: return '受控多选；只读时标签组'
    if '枚举' in typ: return '受控下拉；只读时标签'
    if '数组' in typ: return '分项列表/授权多选关联；每项可查看'
    if '标识' in typ: return '授权对象搜索选择；标识生成后只读，界面优先业务名称/编号'
    if '结构' in typ or '依据' in typ or '凭证' in typ: return '结构化分组表单/依据摘要，按对象子项契约呈现'
    return '单行文本/只读值；可复制非敏感业务编号'

